impl Font {
    /// Advance per glyph in px at scale 1 (5 wide + 1 spacing).
    pub const ADVANCE: i32 = 6;
    pub const W: i32 = 5;
    pub const H: i32 = 7;

    pub fn glyph(c: char) -> &'static [u8; 7] {
        let key = c.to_ascii_lowercase();
        for (name, g) in GLYPHS {
            if name.starts_with(key) {
                return g;
            }
        }
        &GLYPHS[GLYPHS.len() - 1].1
    }

    /// Text width in px at integer `scale`.
    pub fn width(text: &str, scale: i32) -> i32 {
        text.chars().count() as i32 * Self::ADVANCE * scale - scale
    }
}
